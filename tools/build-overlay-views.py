"""Build static shadow-DOM views from the popup markup; no runtime HTML parsing."""
from html.parser import HTMLParser
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parent.parent


class Panels(HTMLParser):
    def __init__(self):
        super().__init__()
        self.views, self.stack = {}, []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        name = attrs.get('id', '').removesuffix('-screen')
        if not self.stack and name not in ('health', 'review'):
            return
        node = [tag, {key: value or '' for key, value in attrs.items()}, []]
        if self.stack:
            self.stack[-1][2].append(node)
        else:
            node[1].pop('hidden', None)
            node[1].pop('aria-labelledby', None)
            self.views[name] = node
        if tag not in ('input', 'br', 'hr', 'img'):
            self.stack.append(node)

    def handle_endtag(self, tag):
        if self.stack and self.stack[-1][0] == tag:
            self.stack.pop()

    def handle_data(self, data):
        if self.stack and data.strip():
            self.stack[-1][2].append(data.strip())


def build():
    parser = Panels()
    parser.feed((ROOT / 'extension/popup.html').read_text(encoding='utf-8'))
    assert set(parser.views) == {'health', 'review'}
    def clean(node):
        if isinstance(node, str):
            return node
        node[2] = [clean(child) for child in node[2] if isinstance(child, str) or 'data-popup-only' not in child[1]]
        return node
    parser.views = {name: clean(view) for name, view in parser.views.items()}
    source = re.sub(r'/\*.*?\*/', '', (ROOT / 'extension/popup.css').read_text(encoding='utf-8'), flags=re.S)
    rules = []
    for selector, body in re.findall(r'([^{}]+)\{([^{}]+)\}', source):
        selectors = [s.strip() for s in selector.split(',') if s.strip() not in (':root', 'html', 'body')]
        if selectors:
            rules.append(','.join('.workspace-content '+s for s in selectors)+'{'+body.strip()+'}')
    return '''/* Generated by tools/build-overlay-views.py from popup.html and popup.css. */
(() => {
  'use strict';
  const views = ''' + json.dumps(parser.views, ensure_ascii=False, separators=(',', ':')) + ''';
  const css = ''' + json.dumps('\n'.join(rules), ensure_ascii=False) + ''';
  function node(spec) {
    if(typeof spec==='string')return document.createTextNode(spec);
    const element=document.createElement(spec[0]);
    for(const [key,value] of Object.entries(spec[1]))element.setAttribute(key,value);
    for(const child of spec[2])element.append(node(child));
    return element;
  }
  globalThis.CVATWorkspaceViews=Object.freeze({css,mount:(container,name)=>{const view=node(views[name]);container.append(view);return view;}});
})();
'''


if __name__ == '__main__':
    args = argparse.ArgumentParser()
    args.add_argument('--check', action='store_true')
    check = args.parse_args().check
    target = ROOT / 'extension/workspace-views.js'
    expected = build()
    if check:
        assert target.read_text(encoding='utf-8') == expected, 'Run python tools/build-overlay-views.py'
    else:
        target.write_text(expected, encoding='utf-8', newline='\n')
    print('Overlay views verified')
